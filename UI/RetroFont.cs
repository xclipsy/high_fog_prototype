using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace HighFog;

/// <summary>
/// Embedded retro 8x8 bitmap font generator and renderer.
/// Renders crisp pixelated text and UI boxes without requiring external XNB font assets.
/// </summary>
public sealed class RetroFont : IDisposable
{
    private readonly GraphicsDevice _graphicsDevice;
    private readonly Texture2D _pixelTexture;
    private readonly Texture2D _fontTexture;
    private const int CharWidth = 8;
    private const int CharHeight = 8;
    private const int TextureWidth = 128;
    private const int TextureHeight = 128;

    public RetroFont(GraphicsDevice graphicsDevice)
    {
        _graphicsDevice = graphicsDevice;
        
        // Create 1x1 white pixel for UI boxes, bars, frames
        _pixelTexture = new Texture2D(graphicsDevice, 1, 1);
        _pixelTexture.SetData(new[] { Color.White });

        // Generate 128x128 font texture with ASCII 32..127 glyphs
        _fontTexture = new Texture2D(graphicsDevice, TextureWidth, TextureHeight);
        var fontPixels = new Color[TextureWidth * TextureHeight];
        for (int i = 0; i < fontPixels.Length; i++)
            fontPixels[i] = Color.Transparent;

        BuildGlyphData(fontPixels);
        _fontTexture.SetData(fontPixels);
    }

    public Texture2D Pixel => _pixelTexture;
    public Texture2D FontSheet => _fontTexture;

    public void DrawString(SpriteBatch spriteBatch, string text, Vector2 position, Color color, float scale = 2f, bool dropShadow = true)
    {
        if (string.IsNullOrEmpty(text)) return;

        if (dropShadow)
        {
            DrawStringInternal(spriteBatch, text, position + new Vector2(scale, scale), new Color(0, 0, 0, (int)(color.A * 0.8f)), scale);
        }

        DrawStringInternal(spriteBatch, text, position, color, scale);
    }

    public void DrawStringCentered(SpriteBatch spriteBatch, string text, Vector2 center, Color color, float scale = 2f, bool dropShadow = true)
    {
        var size = MeasureString(text, scale);
        var pos = new Vector2(center.X - size.X * 0.5f, center.Y - size.Y * 0.5f);
        DrawString(spriteBatch, text, pos, color, scale, dropShadow);
    }

    public Vector2 MeasureString(string text, float scale = 2f)
    {
        if (string.IsNullOrEmpty(text)) return Vector2.Zero;

        var lines = text.Split('\n');
        var maxWidth = 0;
        foreach (var line in lines)
        {
            if (line.Length > maxWidth) maxWidth = line.Length;
        }

        return new Vector2(maxWidth * CharWidth * scale, lines.Length * (CharHeight + 2) * scale);
    }

    public void DrawBox(SpriteBatch spriteBatch, Rectangle rect, Color fillColor, Color borderColor, int borderWidth = 2)
    {
        // Fill
        spriteBatch.Draw(_pixelTexture, rect, fillColor);

        if (borderWidth > 0 && borderColor.A > 0)
        {
            // Top
            spriteBatch.Draw(_pixelTexture, new Rectangle(rect.X, rect.Y, rect.Width, borderWidth), borderColor);
            // Bottom
            spriteBatch.Draw(_pixelTexture, new Rectangle(rect.X, rect.Bottom - borderWidth, rect.Width, borderWidth), borderColor);
            // Left
            spriteBatch.Draw(_pixelTexture, new Rectangle(rect.X, rect.Y, borderWidth, rect.Height), borderColor);
            // Right
            spriteBatch.Draw(_pixelTexture, new Rectangle(rect.Right - borderWidth, rect.Y, borderWidth, rect.Height), borderColor);
        }
    }

    private void DrawStringInternal(SpriteBatch spriteBatch, string text, Vector2 position, Color color, float scale)
    {
        var startX = position.X;
        var currentPos = position;

        for (int i = 0; i < text.Length; i++)
        {
            char c = text[i];
            if (c == '\n')
            {
                currentPos.X = startX;
                currentPos.Y += (CharHeight + 2) * scale;
                continue;
            }

            int charIndex = c - 32;
            if (charIndex < 0 || charIndex >= 96)
                charIndex = '?' - 32;

            int col = charIndex % 16;
            int row = charIndex / 16;
            var srcRect = new Rectangle(col * CharWidth, row * CharHeight, CharWidth, CharHeight);
            var dstRect = new Rectangle((int)currentPos.X, (int)currentPos.Y, (int)(CharWidth * scale), (int)(CharHeight * scale));

            spriteBatch.Draw(_fontTexture, dstRect, srcRect, color);
            currentPos.X += CharWidth * scale;
        }
    }

    private void BuildGlyphData(Color[] pixels)
    {
        // 8x8 binary bitmap patterns for standard ASCII 32 to 127
        for (int c = 32; c <= 126; c++)
        {
            byte[] glyph = GetGlyphBytes((char)c);
            int charIndex = c - 32;
            int colOffset = (charIndex % 16) * CharWidth;
            int rowOffset = (charIndex / 16) * CharHeight;

            for (int y = 0; y < 8; y++)
            {
                byte rowByte = y < glyph.Length ? glyph[y] : (byte)0;
                for (int x = 0; x < 8; x++)
                {
                    bool isSet = (rowByte & (1 << (7 - x))) != 0;
                    int pixelIndex = (rowOffset + y) * TextureWidth + (colOffset + x);
                    if (pixelIndex >= 0 && pixelIndex < pixels.Length)
                    {
                        pixels[pixelIndex] = isSet ? Color.White : Color.Transparent;
                    }
                }
            }
        }
    }

